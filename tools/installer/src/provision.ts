import {publishDirectory} from './atomic.js';
import { randomBytes, randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile, rename, rm, rmdir, mkdtemp, stat } from 'node:fs/promises';
import path from 'node:path';
import type { InstallationConfig, StewardRole } from '@steward/contracts';
import { parseConfig } from '@steward/platform';

export const PROVISIONER_VERSION = 1;
export const RELEASE = '0.4.0';
export interface ProvisionOptions {
  directory: string;
  sourceRoot: string;
  mode: 'all' | StewardRole;
  workers: number;
  project: string;
  label: string;
  portOffset?: number;
}
export interface Instance {
  key: string;
  role: StewardRole;
  apiPort: number;
  webPort: number;
  installationId: string;
}
export interface Manifest {
  provisionerVersion: 1;
  release: string;
  mode: ProvisionOptions['mode'];
  project: string;
  label: string;
  instances: Instance[];
}
const q = (value: string) => JSON.stringify(value.replaceAll('\\', '/'));
export function renderCompose(manifest: Manifest, sourceRoot: string): string {
  const services: string[] = [];
  const secrets: string[] = [];
  for (const i of manifest.instances) {
    const k = i.key;
    // Build each release artifact once. Other installations reference that exact
    // image tag, avoiding concurrent builds racing to replace the same tag.
    const ownsBuild = manifest.instances.find(candidate => candidate.role === i.role)?.key === k;
    const build = (kind: 'api' | 'web') => ownsBuild ? `
    build:
      context: ${q(sourceRoot)}
      dockerfile: infra/Dockerfile.${kind}
      args: { APP: ${i.role} }` : '';
    services.push(`  ${k}-db:
    image: postgres:17.9-alpine
    restart: unless-stopped
    environment:
      POSTGRES_USER: postgres
      POSTGRES_DB: postgres
      POSTGRES_PASSWORD_FILE: /run/secrets/admin_password
      POSTGRES_INITDB_ARGS: --auth-host=scram-sha-256
    secrets:
      - source: ${k}-admin-password
        target: admin_password
      - source: ${k}-db-password
        target: db_password
    volumes:
      - ${k}-data:/var/lib/postgresql/data
      - type: bind
        source: ${q(path.join(sourceRoot, 'infra/init-db.sh'))}
        target: /docker-entrypoint-initdb.d/01-platform.sh
        read_only: true
    networks: [${k}-data]
    healthcheck:
      test: [CMD-SHELL, "pg_isready -U postgres -d postgres"]
      interval: 3s
      timeout: 3s
      retries: 30
    security_opt: [no-new-privileges:true]
  ${k}-api:
    image: steward-${i.role}-api:${manifest.release}${build('api')}
    pull_policy: never
    restart: unless-stopped
    init: true
    read_only: true
    cap_drop: [ALL]
    security_opt: [no-new-privileges:true]
    environment:
      HOST: 0.0.0.0
      PORT: '3000'
      INSTALLATION_CONFIG_FILE: /etc/steward/installation.json
      DB_HOST: ${k}-db
      DB_NAME: steward
      DB_USER: steward_app
      DB_PASSWORD_FILE: /run/secrets/db_password
      DB_SSL_MODE: disable
    secrets:
      - source: ${k}-db-password
        target: db_password
    volumes:
      - type: bind
        source: ./${k}/installation.json
        target: /etc/steward/installation.json
        read_only: true
    ports: ["127.0.0.1:${i.apiPort}:3000"]
    networks:
      ${k}:
        aliases: [api]
      ${k}-data: {}
    depends_on:
      ${k}-db: { condition: service_healthy }
  ${k}-web:
    image: steward-${i.role}-web:${manifest.release}${build('web')}
    pull_policy: never
    restart: unless-stopped
    read_only: true
    cap_drop: [ALL]
    security_opt: [no-new-privileges:true]
    tmpfs: ["/tmp:uid=101,gid=101,mode=1770"]
    ports: ["127.0.0.1:${i.webPort}:8080"]
    networks: [${k}]
    depends_on:
      ${k}-api: { condition: service_healthy }`);
    secrets.push(`  ${k}-db-password:\n    file: ./${k}/secrets/db-password\n  ${k}-admin-password:\n    file: ./${k}/secrets/admin-password`);
  }
  return `# Generated by Steward provisioner v${PROVISIONER_VERSION}; do not store secrets here.\nname: ${manifest.project}\nservices:\n${services.join('\n')}\nvolumes:\n${manifest.instances.map(i => `  ${i.key}-data:`).join('\n')}\nnetworks:\n${manifest.instances.map(i => `  ${i.key}: {}\n  ${i.key}-data:\n    internal: true`).join('\n')}\nsecrets:\n${secrets.join('\n')}\n`;
}
function validateOptions(o: ProvisionOptions): void {
  if (!['all', 'master', 'worker'].includes(o.mode) || !Number.isInteger(o.workers) || o.workers < 1 || o.workers > 20 ||
      !/^[a-z][a-z0-9-]{1,40}$/.test(o.project) || !o.label.trim() || o.label.length > 90) throw new Error('Invalid provision options');
}
async function exists(p: string): Promise<boolean> {
  try { await stat(p); return true; } catch (e) { if ((e as NodeJS.ErrnoException).code === 'ENOENT') return false; throw e; }
}
export async function provision(o: ProvisionOptions): Promise<{ created: boolean; manifest: Manifest }> {
  validateOptions(o);
  const directory = path.resolve(o.directory);
  await mkdir(path.dirname(directory), { recursive: true });
  const lock = `${directory}.provision-lock`;
  try { await mkdir(lock); } catch { throw new Error('Provisioning lock exists. Check for an active provisioner before removing the lock.'); }
  let staging: string | undefined;
  try {
    const keys: { key: string; role: StewardRole; apiPort: number; webPort: number }[] = [];
    let inferredOffset=0;
    if(o.portOffset===undefined&&await exists(path.join(directory,'manifest.json'))){const prior:Manifest=JSON.parse(await readFile(path.join(directory,'manifest.json'),'utf8'));const first=prior.instances[0];if(first)inferredOffset=first.apiPort-(first.role==='master'?4100:4200+Number(first.key.split('-')[1]));}
    const offset=o.portOffset??inferredOffset;if(!Number.isInteger(offset)||offset<0||offset>50000)throw new Error('Invalid port offset');
    if (o.mode !== 'worker') keys.push({ key: 'master', role: 'master', apiPort: 4100+offset, webPort: 5100+offset });
    if (o.mode !== 'master') for (let n = 1; n <= o.workers; n++) keys.push({ key: `worker-${n}`, role: 'worker', apiPort: 4200 + n+offset, webPort: 5200 + n+offset });
    if (await exists(directory)) {
      const manifest = JSON.parse(await readFile(path.join(directory, 'manifest.json'), 'utf8')) as Manifest;
      if (manifest.provisionerVersion !== PROVISIONER_VERSION || !['0.1.0', '0.2.0', '0.3.0', RELEASE].includes(manifest.release) || manifest.mode !== o.mode ||
          manifest.project !== o.project || manifest.label !== o.label || JSON.stringify(manifest.instances.map(({ installationId: _, ...i }) => i)) !== JSON.stringify(keys)) {
        throw new Error('Existing deployment differs. In-place topology changes and upgrades are not implemented; existing files were preserved.');
      }
      for (const i of manifest.instances) {
        const config = parseConfig(JSON.parse(await readFile(path.join(directory, i.key, 'installation.json'), 'utf8')), i.role);
        if (config.installationId !== i.installationId) throw new Error('Installation identity differs from manifest');
        for (const secret of ['db-password', 'admin-password']) {
          if ((await readFile(path.join(directory, i.key, 'secrets', secret), 'utf8')).trim().length < 24) throw new Error('Invalid existing secret');
        }
      }
      // A rerun never rewrites existing configuration, secrets, or topology.
      if (!(await exists(path.join(directory, 'compose.yaml')))) throw new Error('Existing deployment is incomplete: compose.yaml missing');
      return { created: false, manifest };
    }
    staging = await mkdtemp(path.join(path.dirname(directory), `.${path.basename(directory)}-staging-`));
    const manifest: Manifest = { provisionerVersion: 1, release: RELEASE, mode: o.mode, project: o.project, label: o.label, instances: [] };
    for (const i of keys) {
      const config: InstallationConfig = parseConfig({ configVersion: 1, installationId: randomUUID(), role: i.role,
        entity: { entityId: randomUUID(), displayName: `${o.label} · ${i.key}` } }, i.role);
      manifest.instances.push({ ...i, installationId: config.installationId });
      const base = path.join(staging, i.key);
      await mkdir(path.join(base, 'secrets'), { recursive: true, mode: 0o700 });
      await writeFile(path.join(base, 'installation.json'), JSON.stringify(config, null, 2) + '\n', { flag: 'wx', mode: 0o644 });
      // Compose bind-mounts file secrets without remapping ownership. The private
      // 0700 parent protects them on the host; readable mounts work for both the
      // non-root API and PostgreSQL's distinct UID, including on Linux hosts.
      for (const secret of ['db-password', 'admin-password']) await writeFile(path.join(base, 'secrets', secret), randomBytes(32).toString('hex') + '\n', { flag: 'wx', mode: 0o444 });
    }
    await writeFile(path.join(staging, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', { flag: 'wx' });
    await writeFile(path.join(staging, 'compose.yaml'), renderCompose(manifest, path.resolve(o.sourceRoot)), { flag: 'wx' });
    await publishDirectory(staging, directory);
    staging = undefined;
    return { created: true, manifest };
  } finally {
    if (staging) await rm(staging, { recursive: true, force: true });
    await rmdir(lock);
  }
}
