"""Resolve exact Linux/Python wheel hashes; run in the pinned build image."""
import json
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
subprocess.run([sys.executable, '-m', 'pip', 'install', '--dry-run', '--ignore-installed',
                '--only-binary=:all:', '--report', '/tmp/science-resolution.json',
                '-r', str(root / 'requirements.in')], check=True)
report = json.loads(Path('/tmp/science-resolution.json').read_text())
rows = sorted(f"{p['metadata']['name']}=={p['metadata']['version']} --hash=sha256:{p['download_info']['archive_info']['hashes']['sha256']}"
              for p in report['install'])
(root / 'requirements.lock').write_text('# Python 3.13 / Linux amd64; generated by scripts/lock.py.\n' + '\n'.join(rows) + '\n')
